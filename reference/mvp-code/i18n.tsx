const dicts = { en, ar };
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: keyof Dict) => string };
const I18nContext = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = localStorage.getItem("getit.lang");
    if (saved === "en" || saved === "ar") setLangState(saved);
    else if (navigator.language?.toLowerCase().startsWith("ar")) setLangState("ar");
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem("getit.lang", l);
    setLangState(l);
  }, []);
  const t = useCallback((k: keyof Dict) => dicts[lang][k], [lang]);
  // Radix components (tabs, menus, dialogs) default to LTR unless told otherwise.
  return <I18nContext.Provider value={{ lang, setLang, t }}><DirectionProvider dir={lang === "ar" ? "rtl" : "ltr"}>{children}</DirectionProvider></I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
